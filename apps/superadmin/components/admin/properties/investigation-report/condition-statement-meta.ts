/** Render noteHint template with checked boxes marked as ■ */
export function renderNoteWithChecks(noteHint: string, checkedBoxes: number[]): string {
  if (!noteHint) return '';
  const checked = new Set(checkedBoxes);
  const parts = noteHint.split('□');
  return parts
    .map((p, i) => (i < parts.length - 1 ? p + (checked.has(i) ? '■' : '□') : p))
    .join('');
}
